def apply_formats(name: str) -> list[str]:
    n = (name or "Name").strip()[:20] or "Name"
    spaced = " ".join(n)
    out = []
    for fmt in FORMATS:
        out.append(fmt.replace("{n}", n))
    for fmt in FORMATS[:40]:
        out.append(fmt.replace("{n}", spaced))
    return out
